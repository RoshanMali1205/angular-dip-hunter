#!/usr/bin/env node
/**
 * Sync canonical AMK agent definitions into Claude Code and GitHub Copilot paths.
 *
 * Source: angular-multi-agent-kit/agents/*.md
 * Targets:
 *   - .claude/agents/<name>.md
 *   - .github/agents/<name>.agent.md
 */

import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '../..');
const sourceDir = join(root, 'angular-multi-agent-kit/agents');
const claudeDir = join(root, '.claude/agents');
const copilotDir = join(root, '.github/agents');

const banner = `<!-- Generated by angular-multi-agent-kit/scripts/sync-agents.mjs — edit the canonical file under angular-multi-agent-kit/agents/ -->\n`;

async function sync() {
  await mkdir(claudeDir, { recursive: true });
  await mkdir(copilotDir, { recursive: true });

  const files = (await readdir(sourceDir)).filter((f) => f.endsWith('.md')).sort();
  if (files.length === 0) {
    console.error('[amk:sync] no agent markdown files found in', sourceDir);
    process.exit(1);
  }

  for (const file of files) {
    const name = file.replace(/\.md$/, '');
    const body = await readFile(join(sourceDir, file), 'utf8');
    const content = body.startsWith('---') ? `${banner}${body}` : `${banner}---\n${body}`;

    await writeFile(join(claudeDir, `${name}.md`), content, 'utf8');
    await writeFile(join(copilotDir, `${name}.agent.md`), content, 'utf8');
    console.log(`[amk:sync] ${name} → .claude/agents + .github/agents`);
  }

  console.log(`[amk:sync] synced ${files.length} agents`);
}

sync().catch((err) => {
  console.error('[amk:sync] failed', err);
  process.exit(1);
});
